export type Lang = "en" | "de";
const first: Record<Lang, Record<FirstKey, string>> = { en, de };

// The other texts download when a page that needs them is opened (loadTexts), only in the language
// on show; switching language first loads the groups opened so far in the new language.
type Texts = Partial<Record<Key, string>>;
const groupFiles: Record<TextGroup, Record<Lang, () => Promise<Texts>>> = {
  player: { en: () => import("./texts/playerEn").then((m) => m.playerEn), de: () => import("./texts/playerDe").then((m) => m.playerDe) },
  dev: { en: () => import("./texts/devEn").then((m) => m.devEn), de: () => import("./texts/devDe").then((m) => m.devDe) },
  legal: { en: () => import("./texts/legalEn").then((m) => m.legalEn), de: () => import("./texts/legalDe").then((m) => m.legalDe) },
};
const more: Record<Lang, Texts> = { en: {}, de: {} };
const loaded = new Set<string>();
const loading = new Map<string, Promise<void>>();
const wanted = new Set<TextGroup>();
/** The language on show, and the one last chosen (shown once its texts are there). */
let shown: Lang = "en";
let chosen: Lang = "en";

function loadGroup(group: TextGroup, l: Lang): Promise<void> {
  const id = `${group}.${l}`;
  if (loaded.has(id)) return Promise.resolve();
  let p = loading.get(id);
  if (!p) {
    p = groupFiles[group][l]().then(
      (texts) => {
        Object.assign(more[l], texts);
        loaded.add(id);
      },
      (e) => {
        loading.delete(id);
        throw e;
      },
    );
    loading.set(id, p);
  }
  return p;
}

const missing = (l: Lang) => [...wanted].filter((g) => !loaded.has(`${g}.${l}`));

/** For pages that load on demand: loads the groups of texts they use (in the language on show). */
export function loadTexts(groups: TextGroup[]): Promise<void> {
  for (const g of groups) wanted.add(g);
  return Promise.all(groups.map((g) => loadGroup(g, shown))).then(() => {});
}

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("toki.lang");
    if (saved === "en" || saved === "de") return saved;
  } catch {
    /* ignore */
  }
  return navigator.language?.toLowerCase().startsWith("de") ? "de" : "en";
}

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key, vars?: Record<string, string | number>) => string;
}
const I18nContext = createContext<I18n>(null!);

/** Fills in {name} placeholders. "one|many" strings pick a form by the number n. */
/** "Saves, leaderboard and friend invites" (German keeps its nouns capitalized). */
export function listOf(parts: string[], lang: "en" | "de"): string {
  const words = parts.map((w, i) => (i > 0 && lang === "en" ? w.charAt(0).toLowerCase() + w.slice(1) : w));
  if (words.length < 2) return words[0] ?? "";
  return `${words.slice(0, -1).join(", ")} ${lang === "de" ? "und" : "and"} ${words[words.length - 1]}`;
}

export function format(text: string, vars?: Record<string, string | number>): string {
  let s = text;
  if (s.includes("|") && typeof vars?.n === "number") s = s.split("|")[vars.n === 1 ? 0 : 1];
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => (shown = chosen = initialLang()));
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = (l: Lang) => {
    chosen = l;
    try {
      localStorage.setItem("toki.lang", l);
    } catch {
      /* ignore */
    }
    const show = () => {
      shown = l;
      setLangState(l);
    };
    // Until the texts in the new language are there, the page stays in the current one.
    const switchWhenReady = () => {
      if (chosen !== l) return; // another language was chosen meanwhile
      const need = missing(l);
      if (!need.length) return show();
      // If they can't be loaded (offline, or a newer Toki is live), switch all the same: those
      // texts stay in the other language until the page is loaded again.
      Promise.all(need.map((g) => loadGroup(g, l))).then(switchWhenReady, () => chosen === l && show());
    };
    switchWhenReady();
  };
  const other: Lang = lang === "en" ? "de" : "en";
  const t = (key: Key, vars?: Record<string, string | number>) =>
    format(first[lang][key as FirstKey] ?? more[lang][key] ?? more[other][key] ?? key, vars);
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
