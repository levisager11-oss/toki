export type Lang = "en" | "de";
const dicts: Record<Lang, Record<Key, string>> = { en, de };

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("toki.lang");
    if (saved === "en" || saved === "de") return saved;
  } catch {
    /* ignore */
  }
  return navigator.language?.toLowerCase().startsWith("de") ? "de" : "en";
}

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: Key, vars?: Record<string, string>) => string;
}
const I18nContext = createContext<I18n>(null!);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  useEffect(() => {
    document.documentElement.lang = lang;
  }, [lang]);
  const setLang = (l: Lang) => {
    setLangState(l);
    try {
      localStorage.setItem("toki.lang", l);
    } catch {
      /* ignore */
    }
  };
  const t = (key: Key, vars?: Record<string, string>) => {
    let s = dicts[lang][key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, v);
    return s;
  };
  return <I18nContext.Provider value={{ lang, setLang, t }}>{children}</I18nContext.Provider>;
}

export const useI18n = () => useContext(I18nContext);
